#!/bin/sh
# Prints the secret settings of a deployment with new random values (ADR 0015). The values
# contain letters and digits only, so they need no quoting in .env, in a URL or in YAML.
#
#   umask 077
#   cp env.example .env
#   ./generate-secrets.sh >> .env
#
# Run it once per deployment. In the two-host form, run it on the data host and copy the
# printed lines to the .env of the public host: both hosts need the same values.
set -eu

if ! command -v openssl >/dev/null 2>&1; then
    echo "generate-secrets.sh needs openssl" >&2
    exit 1
fi

random_hex() {
    openssl rand -hex "$1"
}

echo "# Generated by generate-secrets.sh on $(date -u +%Y-%m-%d). Keep this file readable for its owner only."
echo "JUNTO_POSTGRES_PASSWORD=$(random_hex 32)"
echo "JUNTO_LIVEKIT_API_KEY=API$(random_hex 8)"
echo "JUNTO_LIVEKIT_API_SECRET=$(random_hex 32)"
echo "JUNTO_REDIS_PASSWORD=$(random_hex 32)"
